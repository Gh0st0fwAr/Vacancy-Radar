def _avg(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return None
    return round(statistics.mean(vals), 1)


def _esc(s):
    return (
        str(s or "")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def _cell(v):
    return "-" if v is None else str(v)


def _html(rows):
    cursor_rows = [r for r in rows if r.get("source") == "cursor"]
    avg_ms = _avg([r.get("elapsed_ms") for r in cursor_rows])
    avg_tok = _avg([r.get("totalTokens") for r in cursor_rows])
    avg_in = _avg([r.get("inputTokens") for r in cursor_rows])
    avg_out = _avg([r.get("outputTokens") for r in cursor_rows])
    trs = []
    for r in rows:
        trs.append(
            "<tr>"
            "<td>" + _esc(r.get("title")) + "</td>"
            "<td>" + str(r.get("score")) + "</td>"
            "<td>" + ("yes" if r.get("accept") else "no") + "</td>"
            "<td>" + _esc(r.get("source")) + "</td>"
            "<td>" + str(r.get("elapsed_ms")) + "</td>"
            "<td>" + _cell(r.get("inputTokens")) + "</td>"
            "<td>" + _cell(r.get("outputTokens")) + "</td>"
            "<td>" + _cell(r.get("totalTokens")) + "</td>"
            "<td>" + _esc("; ".join(r.get("reasons") or [])) + "</td>"
            "</tr>"
        )
    return (
        "<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\"/>"
        "<title>VacancyRadar Cursor scoring bench</title>"
        "<style>"
        "body{font-family:Segoe UI,sans-serif;background:#111827;color:#e5e7eb;margin:24px}"
        "h1{color:#5eead4}table{border-collapse:collapse;width:100%;font-size:14px}"
        "th,td{border:1px solid #334155;padding:8px 10px;text-align:left;vertical-align:top}"
        "th{background:#1f2937;color:#94a3b8}"
        ".summary{background:#1a2332;padding:16px;border-radius:8px;margin-bottom:20px}"
        ".note{color:#94a3b8;font-size:13px}"
        "</style></head><body>"
        "<h1>Cursor scoring - bench report</h1>"
        "<div class=\"summary\">"
        "<p><b>Samples:</b> " + str(len(rows))
        + " | <b>Cursor OK:</b> " + str(len(cursor_rows)) + "</p>"
        "<p><b>Avg time / vacancy (Cursor):</b> "
        + str(avg_ms if avg_ms is not None else "n/a") + " ms</p>"
        "<p><b>Avg tokens / vacancy:</b> total "
        + str(avg_tok if avg_tok is not None else "n/a")
        + " (in " + str(avg_in if avg_in is not None else "n/a")
        + " / out " + str(avg_out if avg_out is not None else "n/a") + ")</p>"
        "<p class=\"note\">If usage columns are empty, SDK did not return token usage. "
        "Generated by tools/bench_cursor_score.py</p></div>"
        "<table><thead><tr>"
        "<th>Vacancy</th><th>Score</th><th>Accept</th><th>Source</th>"
        "<th>Elapsed ms</th><th>Input tok</th><th>Output tok</th>"
        "<th>Total tok</th><th>Reasons</th>"
        "</tr></thead><tbody>"
        + "".join(trs)
        + "</tbody></table></body></html>"
    )


def main():
    cfg = dict(load_config())
    cfg["scoring_mode"] = "cursor"
    rows = []
    print("Bench Cursor scoring, n=", len(SAMPLES), flush=True)
    for i, s in enumerate(SAMPLES, 1):
        print("[" + str(i) + "/" + str(len(SAMPLES)) + "] " + s["title"] + " ...", flush=True)
        t0 = time.perf_counter()
        sc, reasons, ok, meta = score_for_search(
            title=s["title"],
            snippet=s["snippet"],
            salary_text=s.get("salary") or "",
            schedule=s.get("schedule") or "remote",
            company=s.get("company") or "",
            cfg=cfg,
        )
        wall = (time.perf_counter() - t0) * 1000
        usage = meta.get("usage") or {}
        row = {
            "title": s["title"],
            "score": sc,
            "accept": ok,
            "source": meta.get("source"),
            "elapsed_ms": meta.get("elapsed_ms") or round(wall),
            "wall_ms": round(wall),
            "inputTokens": usage.get("inputTokens"),
            "outputTokens": usage.get("outputTokens"),
            "totalTokens": usage.get("totalTokens"),
            "reasons": reasons,
        }
        rows.append(row)
        print(
            "  ->",
            row["source"],
            "score",
            sc,
            "ms",
            row["elapsed_ms"],
            "tok",
            row["totalTokens"],
            flush=True,
        )

    out_dir = ROOT / "data"
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "cursor_score_bench.json"
    html_path = out_dir / "cursor_score_report.html"
    json_path.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    html_path.write_text(_html(rows), encoding="utf-8")
    print("Wrote", json_path, flush=True)
    print("Wrote", html_path, flush=True)


if __name__ == "__main__":
    main()
